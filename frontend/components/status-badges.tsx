import { cn } from "@/lib/utils";
import {
  APPROVAL_LABEL,
  CLAIM_STATUS_HELP,
  CLAIM_STATUS_LABEL,
  RETRIEVAL_LABEL,
  WAIT_LABEL,
} from "@/lib/format";
import type { ApprovalStatus, ClaimStatus, ExternalWaitKind, RetrievalStatus } from "@/types";

const base =
  "inline-flex items-center gap-1 whitespace-nowrap rounded-md border px-1.5 py-0.5 text-[11px] font-medium leading-none";

const CLAIM_TONE: Record<ClaimStatus, string> = {
  tested: "border-sky-500/30 bg-sky-500/10 text-sky-300",
  cross_checked: "border-teal-500/30 bg-teal-500/10 text-teal-300",
  officially_documented: "border-emerald-500/30 bg-emerald-500/10 text-emerald-300",
  inferred: "border-amber-500/30 bg-amber-500/10 text-amber-300",
  estimated: "border-violet-500/30 bg-violet-500/10 text-violet-300",
  unknown: "border-zinc-500/30 bg-zinc-500/10 text-zinc-300",
};

export function ClaimStatusBadge({ status, className }: { status: ClaimStatus; className?: string }) {
  return (
    <span className={cn(base, CLAIM_TONE[status], className)} title={CLAIM_STATUS_HELP[status]}>
      <span className="size-1.5 rounded-full bg-current" aria-hidden />
      {CLAIM_STATUS_LABEL[status]}
    </span>
  );
}

const APPROVAL_TONE: Record<ApprovalStatus, string> = {
  required: "border-rose-500/30 bg-rose-500/10 text-rose-300",
  conditional: "border-amber-500/30 bg-amber-500/10 text-amber-300",
  not_required: "border-emerald-500/30 bg-emerald-500/10 text-emerald-300",
  unclear: "border-zinc-500/30 bg-zinc-500/10 text-zinc-300",
};

export function ApprovalBadge({ status }: { status: ApprovalStatus }) {
  return <span className={cn(base, APPROVAL_TONE[status])}>{APPROVAL_LABEL[status]}</span>;
}

const WAIT_TONE: Record<ExternalWaitKind, string> = {
  none: "border-emerald-500/30 bg-emerald-500/10 text-emerald-300",
  known: "border-sky-500/30 bg-sky-500/10 text-sky-300",
  estimated: "border-violet-500/30 bg-violet-500/10 text-violet-300",
  unknown: "border-zinc-500/30 bg-zinc-500/10 text-zinc-300",
};

export function WaitBadge({ kind }: { kind: ExternalWaitKind }) {
  return <span className={cn(base, WAIT_TONE[kind])}>{WAIT_LABEL[kind]}</span>;
}

const RETRIEVAL_TONE: Record<RetrievalStatus, string> = {
  retrieved: "border-emerald-500/30 bg-emerald-500/10 text-emerald-300",
  snippet_only: "border-amber-500/30 bg-amber-500/10 text-amber-300",
  failed: "border-rose-500/30 bg-rose-500/10 text-rose-300",
  blocked: "border-rose-500/30 bg-rose-500/10 text-rose-300",
  not_attempted: "border-zinc-500/30 bg-zinc-500/10 text-zinc-300",
};

export function RetrievalBadge({ status }: { status: RetrievalStatus | string }) {
  const key = (status in RETRIEVAL_TONE ? status : "not_attempted") as RetrievalStatus;
  const label = status === "discovered" ? "Discovered" : RETRIEVAL_LABEL[key];
  return <span className={cn(base, status === "discovered" ? WAIT_TONE.unknown : RETRIEVAL_TONE[key])}>{label}</span>;
}

export function OriginBadge({ origin }: { origin: string }) {
  return origin === "seed" ? (
    <span className={cn(base, "border-border bg-muted text-muted-foreground")} title="Curated by hand from official docs; not freshly researched">
      Seed guide
    </span>
  ) : (
    <span className={cn(base, "border-primary/30 bg-primary/10 text-primary")} title="Generated by live research">
      Live research
    </span>
  );
}

const RESEARCH_TONE: Record<string, string> = {
  seed_curated: "border-border bg-muted text-muted-foreground",
  complete: "border-emerald-500/30 bg-emerald-500/10 text-emerald-300",
  partial: "border-amber-500/30 bg-amber-500/10 text-amber-300",
  completed: "border-emerald-500/30 bg-emerald-500/10 text-emerald-300",
  running: "border-sky-500/30 bg-sky-500/10 text-sky-300",
  queued: "border-zinc-500/30 bg-zinc-500/10 text-zinc-300",
  failed: "border-rose-500/30 bg-rose-500/10 text-rose-300",
};

const RESEARCH_LABEL: Record<string, string> = {
  seed_curated: "Curated",
  complete: "Evidence complete",
  partial: "Incomplete evidence",
  completed: "Completed",
  running: "Running",
  queued: "Queued",
  failed: "Failed",
};

export function ResearchStatusBadge({ status }: { status: string }) {
  return (
    <span className={cn(base, RESEARCH_TONE[status] ?? RESEARCH_TONE.queued)}>{RESEARCH_LABEL[status] ?? status}</span>
  );
}
